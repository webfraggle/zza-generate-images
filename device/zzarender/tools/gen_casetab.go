//go:build ignore

// gen_casetab writes casetab.h from Go's unicode.CaseRanges so the C++ core
// maps case exactly like strings.ToUpper / strings.ToLower.
//
//	go run device/zzarender/tools/gen_casetab.go > device/zzarender/casetab.h
package main

import (
	"fmt"
	"runtime"
	"unicode"
)

func main() {
	fmt.Println("// GENERATED by tools/gen_casetab.go from Go " + runtime.Version() + " unicode.CaseRanges. Do not edit.")
	fmt.Printf("// Unicode version %s.\n", unicode.Version)
	fmt.Println("#pragma once")
	fmt.Println("#include <cstdint>")
	fmt.Println()
	fmt.Println("// Delta equal to kCaseUpperLower marks an alternating Upper/Lower sequence (as in Go).")
	fmt.Println("static const int32_t kCaseUpperLower = 0x110000;")
	fmt.Println("struct CaseRange { uint32_t lo, hi; int32_t dUpper, dLower; };")
	fmt.Printf("static const CaseRange kCaseRanges[%d] = {\n", len(unicode.CaseRanges))
	for _, cr := range unicode.CaseRanges {
		fmt.Printf("  {0x%X, 0x%X, %d, %d},\n", cr.Lo, cr.Hi, cr.Delta[unicode.UpperCase], cr.Delta[unicode.LowerCase])
	}
	fmt.Println("};")
}
